#!/usr/bin/env python3
"""Colors and measures of the iOS app: docs/tokens.json -> ios/HQR/DesignSystem/Tokens.swift (never by hand).

Light and dark colors become one dynamic Color each; sizes in px become points. `--check` fails when the Swift file is
not what this script writes.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "docs/tokens.json"
OUT = ROOT / "ios/HQR/DesignSystem/Tokens.swift"


def camel(name):
    parts = re.split(r"[-.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def value(node):
    return node["$value"]


def rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def color_literal(hex_color):
    r, g, b = rgb(hex_color)
    return f"UIColor(red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}, alpha: 1)"


def number(text):
    m = re.fullmatch(r"(-?[\d.]+)(px|ms)?", str(text))
    return float(m.group(1)) if m else None


def build():
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    light, dark = tokens["color"]["light"], tokens["color"]["dark"]
    lines = [
        "// Generated by scripts/ios/generate_tokens.py from docs/tokens.json. Do not edit.",
        "import SwiftUI",
        "import UIKit",
        "",
        "/// The colors of docs/tokens.json: each one follows the light or dark appearance.",
        "enum Palette {",
    ]
    for name in sorted(light):
        if name.startswith("$") or name not in dark:
            continue
        lines.append(f"    static let {camel(name)} = Color(UIColor {{ $0.userInterfaceStyle == .dark")
        lines.append(f"        ? {color_literal(value(dark[name]))}")
        lines.append(f"        : {color_literal(value(light[name]))} }})")
    for group in ("black-mode", "reader-background", "illustration"):
        for name, node in sorted(tokens["color"][group].items()):
            if name.startswith("$"):
                continue
            lines.append(f"    static let {camel(group + '-' + name)} = Color({color_literal(value(node))})")
    lines.append(f"    static let seed = Color({color_literal(value(tokens['color']['seed']))})")
    lines += ["}", "", "/// Shapes, spaces and motion of docs/tokens.json, in points and seconds.", "enum Metrics {"]
    for group in ("shape", "space", "motion", "halftone"):
        for name, node in sorted(tokens[group].items()):
            if name.startswith("$"):
                continue
            raw = value(node)
            n = number(raw)
            if n is None:
                continue
            if str(raw).endswith("ms"):
                lines.append(f"    static let {camel(group + '-' + name)}: Double = {n / 1000:g}")
            else:
                lines.append(f"    static let {camel(group + '-' + name)}: CGFloat = {n:g}")
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("Tokens.swift is out of date: python3 scripts/ios/generate_tokens.py")
            sys.exit(1)
        print("Tokens.swift up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)} written")


if __name__ == "__main__":
    main()
